import ts from 'typescript';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const dir=await fs.mkdtemp(path.join(os.tmpdir(),'school-academics-'));
try {
  for(const name of ['metrics','model','actions','reports','results']) {
    const src=await fs.readFile(`lib/school/${name}.ts`,'utf8');
    const js=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText.replace(/(['"])\.\/(model|metrics|results)\1/g,'"./$2.mjs"');
    await fs.writeFile(path.join(dir,name+'.mjs'),js);
  }
  const m=await import(path.join(dir,'model.mjs'));
  const a=await import(path.join(dir,'actions.mjs'));
  const metrics=await import(path.join(dir,'metrics.mjs'));
  const reports=await import(path.join(dir,'reports.mjs'));
  const s=m.newSchool('one','owner',{});s.status='Active';s.years=[{id:'y26',name:'2026',start:'2026-01-01',end:'2026-12-31'},{id:'y27',name:'2027',start:'2027-01-01',end:'2027-12-31'}];s.currentYear='y26';
  const admin={role:'admin',userId:'admin',email:'admin@example.com',name:'Admin'};s.adminEmail=admin.email;
  const teacher={role:'teacher',userId:'rahul',email:'rahul@example.com',teacherId:'rahul',name:'Rahul'};
  s.teachers=[{id:'rahul',firstName:'Rahul',lastName:'Patil',email:teacher.email,status:'Active'},{id:'priya',firstName:'Priya',lastName:'Patil',email:'priya@example.com',status:'Active'}];
  a.applyAction(s,admin,'class',{name:'Class 5',division:'A'});a.applyAction(s,admin,'class',{name:'Class 6',division:'A'});
  const [five,six]=s.classes;
  assert.throws(()=>a.applyAction(s,admin,'class',{name:'class 5',division:'a'}),/already exists/);
  a.applyAction(s,admin,'assignment',{yearId:'y26',teacherId:'rahul',classId:five.id,classTeacher:true});
  a.applyAction(s,admin,'assignment',{yearId:'y26',teacherId:'priya',classId:six.id,classTeacher:true});
  s.students=[{id:'student',firstName:'A',lastName:'B',status:'Active',enrollments:[{id:'e',yearId:'y26',classId:five.id,className:'Class 5',divisionName:'A'}]}];
  const date='2026-09-21';s.attendance=[{id:'present',studentId:'student',yearId:'y26',classId:five.id,date,status:'Present'}];
  assert.throws(()=>a.applyAction(s,teacher,'holiday',{name:'Unauthorized',start:date,end:date}),/School Admin/);
  const invalidBefore=JSON.stringify(s.attendance);
  assert.throws(()=>a.applyAction(s,admin,'attendance',{classId:five.id,yearId:'y26',date,records:{student:'Late'}}),/Mark every student/);
  assert.equal(JSON.stringify(s.attendance),invalidBefore);
  a.applyAction(s,admin,'holiday',{name:'Ganesh Chaturthi',start:'2026-09-22',end:'2026-09-23'});
  assert.equal(metrics.isHoliday(s,'2026-09-20'),true);assert.equal(metrics.isHoliday(s,'2026-09-22'),true);
  assert.throws(()=>a.applyAction(s,teacher,'attendance',{classId:five.id,date:'2026-09-22',records:{student:'Present'}}),/Holiday/);
  const month=metrics.calendarMonth(s,'y26','student','2026-09');
  assert.equal(month.days.find(d=>d.date==='2026-09-20').status,'Holiday');assert.equal(month.days.find(d=>d.date==='2026-09-22').name,'Ganesh Chaturthi');assert.equal(month.percentage,100);
  assert.equal(month.days.length,30);
  assert.equal(month.days.find(d=>d.date==='2026-09-23').status,'Holiday');
  assert.equal(month.days.find(d=>d.date==='2026-09-27').name,'Sunday');
  assert.equal(month.days.find(d=>d.date==='2026-09-28').status,'Future Date');
  assert.equal(month.present,1);assert.equal(month.absent,0);assert.equal(month.percentage,100);
  a.applyAction(s,admin,'holiday',{name:'October Break',start:'2026-10-02',end:'2026-10-03'});
  const nextMonth=metrics.calendarMonth(s,'y26','student','2026-10');
  assert.equal(nextMonth.days.find(d=>d.date==='2026-10-02').name,'October Break');
  assert.equal(nextMonth.days.find(d=>d.date==='2026-10-02').status,'Holiday');
  assert.equal(nextMonth.days.find(d=>d.date==='2026-10-04').name,'Sunday');
  assert.equal(nextMonth.percentage,null);
  a.applyAction(s,admin,'holiday',{id:s.holidays[0].id,name:'Festival',start:'2026-09-22',end:'2026-09-24'});
  assert(metrics.isHoliday(s,'2026-09-24'));
  const holidayId=s.holidays[0].id;a.applyAction(s,admin,'deleteHoliday',{id:holidayId});assert.equal(metrics.isHoliday(s,'2026-09-24'),false);
  a.applyAction(s,admin,'activateYear',{id:'y27'});
  assert.equal(s.classes.length,2);assert.equal(s.assignments.length,2);assert.equal(s.assignments[0].teacherId,'rahul');
  a.applyAction(s,admin,'removeAssignment',{id:s.assignments[0].id,yearId:'y27'});
  a.applyAction(s,admin,'assignment',{yearId:'y27',teacherId:'priya',classId:five.id,classTeacher:true,confirmMulti:true});
  assert.equal(s.assignments.filter(x=>x.classId===six.id).length,1);assert.equal(s.assignmentHistory.y26.find(x=>x.classId===five.id).teacherId,'rahul');
  a.applyAction(s,admin,'class',{id:five.id,name:'Grade 5',division:'A',status:'Inactive'});
  assert.equal(s.students[0].enrollments[0].className,'Class 5');assert.equal(s.classes.length,2);
  const oldScope=reports.reportScope(s,{email:admin.email,userId:admin.userId},new URLSearchParams({role:'admin',academicYearId:'y26',date}));
  assert.equal(oldScope.classes.find(c=>c.id===five.id).name,'Class 5');
  assert.equal(oldScope.options.teachers.some(t=>t.id==='rahul'),true);
  assert.equal(reports.summarizeReport(oldScope,reports.monthlySummary(s,'y26','2026-09')).totals.present,1);
  const legacy=m.newSchool('legacy','owner',{});legacy.status='Active';legacy.years=s.years;legacy.currentYear='y26';legacy.classes=[{id:'old-5',yearId:'y26',name:'Class 5',division:'A'},{id:'new-5',yearId:'y27',name:'Class 5',division:'A'}];legacy.students=[{id:'p',status:'Active',enrollments:[{id:'e1',yearId:'y26',classId:'old-5'},{id:'e2',yearId:'y27',classId:'new-5'}]}];legacy.assignments=[{id:'ta',teacherId:'rahul',classId:'old-5',classTeacher:true}];
  m.normalizeAttendance(legacy);
  assert.equal(legacy.classes.length,1);assert.equal(legacy.students[0].enrollments[0].classId,legacy.students[0].enrollments[1].classId);
  assert.equal(legacy.students[0].enrollments[0].className,'Class 5');assert.equal(legacy.assignmentHistory.y26.length,1);
  a.applyAction(legacy,admin,'activateYear',{id:'y27'});assert.equal(legacy.assignments.length,1);
  console.log('PASS permanent classes, duplicate prevention, assignments carried and selectively changed, historical roster/report, Sunday and managed holiday calendar, excluded holiday attendance, edit/delete holiday');
} finally {await fs.rm(dir,{recursive:true,force:true});}
